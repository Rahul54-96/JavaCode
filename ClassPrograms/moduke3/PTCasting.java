package moduke3;
public class PTCasting 
{
	public static void main(String[] args) 
	{
		//int into double
		int a=100;
		
		double d=	a; //implicit syntax
		System.out.println(d);
		
		double d1=(double)	a; //explicit syntax
		System.out.println(d1);
		
		
		//double into int
		
		double e=90.6;
		int z=(int)	e;//explicit syntax
		System.out.println(z);
		
		
	}
}
