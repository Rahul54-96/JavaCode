package assignments;

import java.util.Arrays;

public class A55_StringScannerArray 
{
    public static void main(String[] args) 
    {
        int[] intArr = {1, 2, 3, 4, 5};
        String[] strArr = {"Ram", "Sham", "Hari"};
        char[] charArr = {'a', 'b', 'c'};

        System.out.println("int[] = " + Arrays.toString(intArr));
        System.out.println("String[] = " + Arrays.toString(strArr));
        System.out.println("char[] = " + Arrays.toString(charArr));
    }
}