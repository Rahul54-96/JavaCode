package assignments;

public class A01_PrintMyName {

	public static void main(String[] args) {
		
		String fName = "Rahul";
		String mName = "Vasant";
		String lName = "Khilare";
		//To print First name, Middle Name and Last name on single line
		System.out.print("My Name is : "+fName+"\t"+mName+"\t"+lName+"\n");
		
		//To print First name, Middle Name and Last name on separate-separate line
		System.out.println("\nMy Name is :\n"+fName);
		System.out.println(mName);
		System.out.println(lName);
		
	}

}
