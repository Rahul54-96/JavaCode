package assignments;

public class A02_DataTypes {

	public static void main(String[] args) {
		byte age = 30;
		short height = 172;
		long empID = 9765958803L;
		int mobNo = 97659588;
		char initial = 'R';
		boolean condition = true;
		float valueOfPi = 3.142f;
		double fullValueOfPi = 3.14159d;
		
		System.out.println("My Age is "+age);
		System.out.println("My Height is "+height);
		System.out.println("My EmployeeID is "+empID);
		System.out.println("My Mobile Number is "+mobNo);
		System.out.println("My name's initial is "+initial);
		System.out.println("Condition is "+condition);
		System.out.println("Round of PI value is "+valueOfPi);
		System.out.println("Value of PI is "+fullValueOfPi);
		
	}

}
